import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root=path.dirname(fileURLToPath(import.meta.url));
const assets=path.resolve(root,"../../app/src/main/assets");
const result=await build({entryPoints:[path.join(root,"dom-entry.js")],bundle:true,format:"iife",platform:"neutral",target:"es2020",minify:true,write:false,legalComments:"eof"});
await writeFile(path.join(assets,"comic-dom-vendor.js"),"/* linkedom 0.18.12; licenses: comic-dom-NOTICES.txt; generated by tools/comic-host/build.mjs */\n"+result.outputFiles[0].text);
const notices=[];
async function collect(dir) {
  for(const entry of await readdir(dir,{withFileTypes:true})) {
    if(!entry.isDirectory()||entry.name.startsWith('.'))continue;
    const folder=path.join(dir,entry.name);
    if(entry.name.startsWith('@')) { await collect(folder);continue; }
    try {
      const pkg=JSON.parse(await readFile(path.join(folder,"package.json"),"utf8"));
      const files=(await readdir(folder)).filter(f=>/^(license|copying)(\.|$)/i.test(f));
      for(const file of files)notices.push(`${pkg.name} ${pkg.version}\n${await readFile(path.join(folder,file),"utf8")}`);
      try { await collect(path.join(folder,"node_modules")); } catch {}
    } catch {}
  }
}
await collect(path.join(root,"node_modules"));
await writeFile(path.join(assets,"comic-dom-NOTICES.txt"),"Bundled HTML parser and build dependencies. Package versions are locked in tools/comic-host/package-lock.json.\n\n"+notices.join("\n\n--------------------\n\n"));
console.log(`HTML parser bundled: ${result.outputFiles[0].contents.length} bytes; ${notices.length} license notices.`);
